#!/bin/bash
# Build, sign, install, and register the glucose widget. Re-run this any time
# you change the code or config.env. Requires:
#   - Xcode + an Apple ID signed into Xcode → Settings → Accounts (free is fine)
#   - xcodegen (brew install xcodegen)
#   - config.env (copy config.env.example and fill it in)
set -euo pipefail
cd "$(dirname "$0")"

APP_NAME="GlucoseWidget"

if [[ ! -f config.env ]]; then
  echo "❌ config.env not found. Run: cp config.env.example config.env  — then fill it in."
  exit 1
fi
# shellcheck disable=SC1091
source config.env

for var in DEVELOPMENT_TEAM BUNDLE_ID_PREFIX GLUCOSE_ENDPOINT; do
  if [[ -z "${!var:-}" ]]; then
    echo "❌ $var is empty in config.env."
    exit 1
  fi
done
export DEVELOPMENT_TEAM BUNDLE_ID_PREFIX
GLUCOSE_API_TOKEN="${GLUCOSE_API_TOKEN:-}"

command -v xcodegen >/dev/null || { echo "❌ xcodegen missing. Run: brew install xcodegen"; exit 1; }
command -v xcodebuild >/dev/null || { echo "❌ Xcode missing. Install it from the App Store."; exit 1; }

# Escape backslashes and quotes so the values are safe inside a Swift string.
swift_escape() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }

echo "[$(date +%H:%M:%S)] Writing Widget/Config.generated.swift…"
cat > Widget/Config.generated.swift <<SWIFT
// Generated by install.sh from config.env. Do not edit or commit.
enum GeneratedConfig {
    static let endpoint = "$(swift_escape "$GLUCOSE_ENDPOINT")"
    static let apiToken = "$(swift_escape "$GLUCOSE_API_TOKEN")"
}
SWIFT

echo "[$(date +%H:%M:%S)] Generating Xcode project…"
xcodegen generate >/dev/null

echo "[$(date +%H:%M:%S)] Building signed Release…"
rm -rf build
xcodebuild -project "$APP_NAME.xcodeproj" -scheme "$APP_NAME" \
  -configuration Release -destination 'platform=macOS' \
  -allowProvisioningUpdates DEVELOPMENT_TEAM="$DEVELOPMENT_TEAM" \
  CONFIGURATION_BUILD_DIR="$PWD/build" build >/dev/null

echo "[$(date +%H:%M:%S)] Installing to /Applications…"
osascript -e "quit app \"$APP_NAME\"" 2>/dev/null || true
sleep 1
rm -rf "/Applications/$APP_NAME.app"
cp -R "build/$APP_NAME.app" /Applications/

LSREGISTER=/System/Library/Frameworks/CoreServices.framework/Versions/Current/Frameworks/LaunchServices.framework/Versions/Current/Support/lsregister
"$LSREGISTER" -f -R -trusted "/Applications/$APP_NAME.app"

echo "[$(date +%H:%M:%S)] Launching host app so the widget registers…"
open "/Applications/$APP_NAME.app"
sleep 5

echo "[$(date +%H:%M:%S)] Verifying widget registration…"
if pluginkit -m -i "$BUNDLE_ID_PREFIX.GlucoseWidgetExtension" | grep -q GlucoseWidgetExtension; then
  echo "✅ Widget registered. Add it from Notification Center → Edit Widgets → \"Glucose\"."
else
  echo "⚠️  Widget not registered yet. See docs/TROUBLESHOOTING.md."
fi
